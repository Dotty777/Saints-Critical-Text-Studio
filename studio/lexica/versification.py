# Cross-language pairing for extra-site verses whose numbering differs across streams and that have no
# Studio Greek verse to bridge them (currently only MT Ps 116:14 == Vulgate/LXX Ps 115:5).
_EXTRA_SITE_ALIGN: Dict[Tuple[str, str, int, int], Ref] = {
    ("hebrew", "psalms", 116, 14): (115, 5),
}


def is_duplicate_or_placeholder(lang: str, book_slug: str, chapter: int, verse: int) -> bool:
    """True for confirmed duplicate/stray-title/placeholder verses that must never be indexed."""
    return (_norm_lang(lang), book_slug, int(chapter), int(verse)) in _DUPLICATE_OR_PLACEHOLDER


def to_extra_site_anchor(lang: str, book_slug: str, chapter: int, verse: int) -> Optional[Ref]:
    """Non-site anchor (chapter, verse) for a genuine non-duplicate verse absent from Saints.Bible.

    Returns None when the verse maps to a live Saints.Bible verse (use ``to_saints`` with subverse=0),
    when the language lacks the book, or when the verse is a confirmed duplicate or placeholder.
    Cross-language verses share one anchor via ``to_studio_greek`` (Theodotion Daniel, 2 Kgs 25:10,
    NT TR verses) or ``_EXTRA_SITE_ALIGN`` (MT Ps 116:14 == Vulgate Ps 115:5), and otherwise keep their
    shared MT/Vulgate (chapter, verse).
    """
    lang = _norm_lang(lang)
    chapter, verse = int(chapter), int(verse)
    if book_slug not in inventory(lang):
        return None
    if to_saints(lang, book_slug, chapter, verse):
        return None
    if is_duplicate_or_placeholder(lang, book_slug, chapter, verse):
        return None
    aligned = _EXTRA_SITE_ALIGN.get((lang, book_slug, chapter, verse))
    if aligned is not None:
        return aligned
    if lang != "greek":
        sg = to_studio_greek(lang, book_slug, chapter, verse)
        if sg:
            return sg[0]
    return (chapter, verse)


@lru_cache(maxsize=None)
def _reverse_extra(lang: str) -> Dict[Tuple[str, int, int], Tuple[Ref, ...]]:
    lang = _norm_lang(lang)
    rev: Dict[Tuple[str, int, int], List[Ref]] = defaultdict(list)
    for book, chapters in inventory(lang).items():
        for c, vs in chapters.items():
            for v in vs:
                anc = to_extra_site_anchor(lang, book, c, v)
                if anc is not None:
                    rev[(book,) + anc].append((c, v))
    return {k: tuple(sorted(vs)) for k, vs in rev.items()}


def from_extra_site_anchor(lang: str, book_slug: str, chapter: int, verse: int) -> List[Ref]:
    """The verses of ``lang`` (Studio numbering) filed under this extra-site anchor (subverse=9)."""
    return list(_reverse_extra(_norm_lang(lang)).get((book_slug, int(chapter), int(verse)), ()))


def _studio_verses(conn: sqlite3.Connection, lang: str) -> Dict[str, Dict[int, set]]:
    out: Dict[str, Dict[int, set]] = defaultdict(lambda: defaultdict(set))
    rows = conn.execute(
        "SELECT ch.book_slug, ch.chapter, v.verse FROM verses v JOIN chapters ch ON ch.id = v.chapter_id "
        "WHERE ch.language = ?", (lang,))
    for book, c, v in rows:
        out[book][int(c)].add(int(v))
    return out


def coverage_report(conn: sqlite3.Connection) -> Dict[str, dict]:
    """Per language and book: verses in the live Studio DB, mapped / unmapped to Saints.Bible, one-to-many,
    many-to-one, targets missing from the site inventory (must be 0), Studio Greek intermediate targets
    missing from the live Studio Greek (must be 0) and drift from the snapshot inventories.

    The 'greek' entry also reports how the Studio Greek numbering differs from the site: per book,
    ``renumbered`` (Studio Greek verses whose Saints.Bible verse is not the same chapter:verse, listed in
    ``renumbered_refs`` as 'c:v>c:v[,c:v]'), ``unmapped`` (no site counterpart) and ``site_only`` (site
    verses no Studio Greek verse reaches, listed in ``site_only_refs``).

    ``conn`` should be opened read-only (``sqlite3.connect('file:...?mode=ro', uri=True)``); nothing is written.
    """
    greek_live = _studio_verses(conn, "greek")
    site = inventory(SAINTS)
    report: Dict[str, dict] = {}
    for lang in LANGS:
        live = _studio_verses(conn, lang)
        snap = inventory(lang)
        books: Dict[str, dict] = {}
        tot: Dict[str, int] = defaultdict(int)
        for book in sorted(live):
            row: Dict[str, int] = defaultdict(int)
            unmapped: List[str] = []
            renumbered: List[str] = []
            hits: Dict[Ref, int] = defaultdict(int)
            for c in sorted(live[book]):
                for v in sorted(live[book][c]):
                    row["verses"] += 1
                    if v not in snap.get(book, {}).get(c, ()):
                        row["not_in_snapshot"] += 1
                    if lang != "greek":
                        for g in to_studio_greek(lang, book, c, v):
                            if g[1] not in greek_live.get(book, {}).get(g[0], ()):
                                row["studio_greek_target_missing_in_db"] += 1
                    ts = to_saints(lang, book, c, v)
                    if not ts:
                        row["unmapped"] += 1
                        unmapped.append("%d:%d" % (c, v))
                        continue
                    row["mapped"] += 1
                    if len(ts) > 1:
                        row["one_to_many"] += 1
                    if ts != [(c, v)]:
                        row["renumbered"] += 1
                        if lang == "greek":
                            renumbered.append("%d:%d>%s" % (c, v, ",".join("%d:%d" % t for t in ts)))
                    for t in ts:
                        hits[t] += 1
                        if t[1] not in site.get(book, {}).get(t[0], ()):
                            row["target_missing_on_site"] += 1
            row["saints_verses_hit"] = len(hits)
            row["saints_verses_many_to_one"] = sum(1 for n in hits.values() if n > 1)
            for c, vs in snap.get(book, {}).items():
                row["snapshot_not_in_db"] += sum(1 for v in vs if v not in live[book].get(c, ()))
            entry: dict = dict(row)
            entry["unmapped_refs"] = unmapped
            if lang == "greek":
                site_only = ["%d:%d" % (c, v) for c, vs in sorted(site.get(book, {}).items())
                             for v in sorted(vs) if (c, v) not in hits]
                entry["site_only"] = len(site_only)
                entry["site_only_refs"] = site_only
                entry["renumbered_refs"] = renumbered
                tot["site_only"] += len(site_only)
            books[book] = entry
            for k, n in row.items():
                tot[k] += n
        totals = dict(tot)
        totals["share_mapped"] = round(totals.get("mapped", 0) / totals["verses"], 4) if totals.get("verses") else 0.0
        report[lang] = {"books": books, "totals": totals, "source": SOURCES[lang]}
    return report


def _cli() -> None:  # pragma: no cover - convenience only
    import argparse
    import json
    import os

    ap = argparse.ArgumentParser(description="Saints.Bible versification coverage (read-only)")
    ap.add_argument("--db", default=os.path.join(os.path.dirname(__file__), "..", "..", "data", "studio.db"))
    args = ap.parse_args()
    path = os.path.abspath(args.db).replace("\\", "/")
    conn = sqlite3.connect("file:%s?mode=ro" % path, uri=True)
    rep = coverage_report(conn)
    print(json.dumps({lang: rep[lang]["totals"] for lang in rep}, indent=1))


if __name__ == "__main__":  # pragma: no cover
    _cli()
