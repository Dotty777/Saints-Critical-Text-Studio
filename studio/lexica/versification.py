def to_studio_greek(lang: str, book_slug: str, chapter: int, verse: int) -> List[Ref]:
    """Studio Greek (Swete) (chapter, verse) refs for a verse numbered as stored in the Studio for ``lang``.

    Identity for 'greek' (when the Studio Greek has the verse).  Empty when the Studio Greek has no
    counterpart.  This is the first step of ``to_saints``.
    """
    lang = _norm_lang(lang)
    chapter, verse = int(chapter), int(verse)
    if lang != "greek":
        if book_slug not in inventory(lang):
            return []  # the language has no such book in the Studio (e.g. no Hebrew Sirach or NT)
        hit = _rule_table(lang).get((book_slug, chapter, verse))
        if hit is not None:
            return list(hit)
    return [(chapter, verse)] if studio_greek_has(book_slug, chapter, verse) else []


def _greek_to_saints(book_slug: str, chapter: int, verse: int) -> List[Ref]:
    hit = _rule_table("greek").get((book_slug, chapter, verse))
    if hit is not None:
        return list(hit)
    return [(chapter, verse)] if saints_has(book_slug, chapter, verse) else []


def to_saints(lang: str, book_slug: str, chapter: int, verse: int) -> List[Ref]:
    """Live Saints.Bible (chapter, verse) refs for a verse numbered as stored in the Studio for ``lang``.

    Empty list when the site has no counterpart (or none could be established).  Usually one target;
    several when the site divides the text differently, the first holding most of the verse.
    """
    lang = _norm_lang(lang)
    chapter, verse = int(chapter), int(verse)
    if lang == "greek":
        if book_slug not in inventory("greek"):
            return []
        return _greek_to_saints(book_slug, chapter, verse)
    if book_slug not in inventory(lang):
        return []
    hit = _site_rule_table(lang).get((book_slug, chapter, verse))
    if hit is not None:
        return list(hit)
    out: List[Ref] = []
    for g in to_studio_greek(lang, book_slug, chapter, verse):
        for t in _greek_to_saints(book_slug, *g):
            if t not in out:
                out.append(t)
    return out


@lru_cache(maxsize=None)
def _reverse(lang: str) -> Dict[Tuple[str, int, int], Tuple[Ref, ...]]:
    lang = _norm_lang(lang)
    rev: Dict[Tuple[str, int, int], List[Ref]] = defaultdict(list)
    inv = inventory(lang)
    for book, chapters in inv.items():
        for c, vs in chapters.items():
            for v in vs:
                for t in to_saints(lang, book, c, v):
                    rev[(book,) + t].append((c, v))
    # verses named by a rule but absent from the snapshot inventory still reverse-map
    extra = set(_site_rule_table(lang)) | set(_rule_table(lang))
    for book, c, v in extra:
        if book in inv and v not in inv[book].get(c, ()):
            for t in to_saints(lang, book, c, v):
                if (c, v) not in rev[(book,) + t]:
                    rev[(book,) + t].append((c, v))
    return {k: tuple(sorted(vs)) for k, vs in rev.items()}


def from_saints(lang: str, book_slug: str, chapter: int, verse: int) -> List[Ref]:
    """The verses of ``lang`` (Studio numbering) whose counterpart includes this Saints.Bible verse."""
    return list(_reverse(_norm_lang(lang)).get((book_slug, int(chapter), int(verse)), ()))


def map_chapter(lang: str, book_slug: str, chapter: int, verses: Iterable[int]) -> Dict[int, List[Ref]]:
    """to_saints for every verse of one Studio chapter."""
    return {int(v): to_saints(lang, book_slug, chapter, v) for v in verses}


