def _norm_lang(lang: str) -> str:
    try:
        return _LANG_ALIASES[lang.lower()]
    except (KeyError, AttributeError):
        raise ValueError("unknown language %r (expected one of %s)" % (lang, ", ".join(LANGS)))


@lru_cache(maxsize=None)
def _parse_inventory(key: str) -> Dict[str, Dict[int, frozenset]]:
    out: Dict[str, Dict[int, frozenset]] = {}
    for line in _INVENTORY[key].strip().splitlines():
        parts = line.split()
        book, chapters = parts[0], {}
        for tok in parts[1:]:
            m = re.fullmatch(r"(\d+):(\d+)(?:/([\d.]+))?", tok)
            if not m:
                raise ValueError("bad inventory token %r (%s)" % (tok, book))
            gaps = {int(g) for g in m.group(3).split(".")} if m.group(3) else set()
            chapters[int(m.group(1))] = frozenset(v for v in range(1, int(m.group(2)) + 1) if v not in gaps)
        out[book] = chapters
    return out


def inventory(lang: str) -> Dict[str, Dict[int, frozenset]]:
    """{book_slug: {chapter: frozenset(verse numbers)}} of a Studio stream (snapshot), or of the live
    Saints.Bible numbering when ``lang`` is ``'saints'``."""
    return _parse_inventory(SAINTS if lang == SAINTS else _norm_lang(lang))


def saints_has(book_slug: str, chapter: int, verse: int) -> bool:
    """True when the live Saints.Bible numbering has this verse (lettered parts folded in)."""
    return verse in inventory(SAINTS).get(book_slug, {}).get(chapter, ())


def studio_greek_has(book_slug: str, chapter: int, verse: int) -> bool:
    """True when the Studio Greek stream (snapshot) has this verse."""
    return verse in inventory("greek").get(book_slug, {}).get(chapter, ())


def _expand(spec: str) -> List[Ref]:
    out: List[Ref] = []
    for part in spec.split(","):
        m = re.fullmatch(r"(\d+):(\d+)(?:-(\d+))?", part.strip())
        if not m:
            raise ValueError("bad reference %r" % spec)
        c, a = int(m.group(1)), int(m.group(2))
        out.extend((c, v) for v in range(a, int(m.group(3) or a) + 1))
    return out


def _parse_rules(text: str) -> Dict[Tuple[str, int, int], Tuple[Ref, ...]]:
    table: Dict[Tuple[str, int, int], Tuple[Ref, ...]] = {}
    for raw in text.strip().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        book, src = parts[0], _expand(parts[1])
        if len(parts) == 3 and parts[2] == "-":
            for c, v in src:
                table[(book, c, v)] = ()
            continue
        if len(parts) != 4 or parts[2] not in ("=", "in", ">"):
            raise ValueError("bad rule %r" % raw)
        dst = _expand(parts[3])
        if parts[2] == "=":
            if len(src) != len(dst):
                raise ValueError("unequal ranges in %r" % raw)
            for s, d in zip(src, dst):
                table[(book,) + s] = (d,)
        elif parts[2] == "in":
            if len(dst) != 1:
                raise ValueError("'in' needs one target: %r" % raw)
            for s in src:
                table[(book,) + s] = (dst[0],)
        else:
            if len(src) != 1:
                raise ValueError("'>' needs one source verse: %r" % raw)
            table[(book,) + src[0]] = tuple(dst)
    return table


@lru_cache(maxsize=None)
def _rule_table(lang: str) -> Dict[Tuple[str, int, int], Tuple[Ref, ...]]:
    """'hebrew' / 'latin': source -> Studio Greek.  'greek': Studio Greek -> Saints.Bible."""
    return _parse_rules(_RULES[_norm_lang(lang)])


@lru_cache(maxsize=None)
def _site_rule_table(lang: str) -> Dict[Tuple[str, int, int], Tuple[Ref, ...]]:
    lang = _norm_lang(lang)
    return _parse_rules(_SITE_RULES[lang]) if lang in _SITE_RULES else {}


